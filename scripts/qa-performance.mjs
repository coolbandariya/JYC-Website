import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const dist=path.join(root,'dist');
if(!fs.existsSync(dist)) throw new Error('Performance QA requires a production build in dist/. Run npm run build first.');
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(entry=>{const p=path.join(dir,entry.name);return entry.isDirectory()?walk(p):[p]});
const files=walk(dist);
const js=files.filter(f=>f.endsWith('.js'));
const css=files.filter(f=>f.endsWith('.css'));
const images=files.filter(f=>/\.(?:png|jpe?g|webp|avif|gif|svg)$/i.test(f));
const bytes=fs.statSync;
const total=list=>list.reduce((n,f)=>n+bytes(f).size,0);
const largest=list=>list.length?Math.max(...list.map(f=>bytes(f).size)):0;
const fmt=n=>(n/1024).toFixed(1)+' KiB';
const failures=[];
const check=(name,ok,detail='')=>{console.log((ok?'PASS':'FAIL')+': '+name+(detail?' — '+detail:''));if(!ok)failures.push(name)};
const html=fs.readFileSync(path.join(dist,'index.html'),'utf8');
check('production index exists',true);
check('hashed JS output is present',js.length>0,js.length+' JS files');
check('hashed CSS output is present',css.length>0,css.length+' CSS files');
check('JS total stays within 1.5 MiB',total(js)<=1572864,fmt(total(js)));
check('largest JS chunk stays within 500 KiB',largest(js)<=512000,fmt(largest(js)));
check('CSS total stays within 1.25 MiB',total(css)<=1310720,fmt(total(css)));
check('no individual raster image exceeds 3 MiB',largest(images.filter(f=>!f.endsWith('.svg')))<=3145728,fmt(largest(images.filter(f=>!f.endsWith('.svg')))));
check('entry references hashed build assets',/\/assets\/[^"']+\.(?:js|css)/.test(html));
check('no source-map files ship in production',!files.some(f=>f.endsWith('.map')));
console.log('Performance budget: JS '+fmt(total(js))+', CSS '+fmt(total(css))+', largest JS '+fmt(largest(js)));
if(failures.length) process.exit(1);